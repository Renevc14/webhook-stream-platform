# Pull staging Supabase + crypto credentials from AWS Secrets Manager into
# backend/image-to-cell-3/.env.staging for migrate_encrypt_webhook_secrets.py.
#
# Does NOT modify your local .env (dev/sandbox). The migration script reads
# --env-file .env.staging so you can keep both environments side by side.
#
# Prereq: aws sso login --profile smarthub-staging
# Usage (from repo root):
#   powershell -ExecutionPolicy Bypass -File backend/image-to-cell-3/scripts/prepare-stg-migration-env.ps1

param(
  [string] $Region = "eu-west-2",
  [string] $Profile = "smarthub-staging",
  [string] $SecretId = "stg/image-to-cell-env"
)

$ErrorActionPreference = "Stop"
$OutDir = Split-Path -Parent $PSScriptRoot
$OutFile = Join-Path $OutDir ".env.staging"

$raw = aws secretsmanager get-secret-value `
  --secret-id $SecretId `
  --region $Region `
  --profile $Profile `
  --query "SecretString" `
  --output text

if (-not $raw) { throw "Empty SecretString from $SecretId" }

$obj = $raw | ConvertFrom-Json

$required = @("SUPABASE_URL", "SUPABASE_SERVICE_ROLE_KEY", "APP_CRYPTO_KEY")
$missing = @()
foreach ($key in $required) {
  $val = $obj.$key
  if ($null -eq $val -or [string]::IsNullOrWhiteSpace([string]$val)) {
    $missing += $key
  }
}
if ($missing.Count -gt 0) {
  throw "Secret $SecretId is missing: $($missing -join ', ')"
}

$lines = @(
  "# Auto-generated by prepare-stg-migration-env.ps1 - do not commit",
  "# Used only for: python scripts/migrate_encrypt_webhook_secrets.py --env-file .env.staging",
  "",
  "SUPABASE_URL=$($obj.SUPABASE_URL)",
  "SUPABASE_SERVICE_ROLE_KEY=$($obj.SUPABASE_SERVICE_ROLE_KEY)",
  "APP_CRYPTO_KEY=$($obj.APP_CRYPTO_KEY)",
  ""
)

[System.IO.File]::WriteAllLines($OutFile, $lines, [System.Text.UTF8Encoding]::new($false))

$url = [string]$obj.SUPABASE_URL
Write-Host "Wrote $OutFile" -ForegroundColor Green
Write-Host "  SUPABASE_URL = $url" -ForegroundColor Cyan
Write-Host "  SUPABASE_SERVICE_ROLE_KEY = (set, length $(([string]$obj.SUPABASE_SERVICE_ROLE_KEY).Length))" -ForegroundColor Cyan
Write-Host "  APP_CRYPTO_KEY = (set, length $(([string]$obj.APP_CRYPTO_KEY).Length))" -ForegroundColor Cyan
Write-Host ""
Write-Host "Next:" -ForegroundColor Yellow
Write-Host "  cd backend/image-to-cell-3"
Write-Host "  python scripts/migrate_encrypt_webhook_secrets.py --env-file .env.staging --dry-run"
Write-Host "  python scripts/migrate_encrypt_webhook_secrets.py --env-file .env.staging"
