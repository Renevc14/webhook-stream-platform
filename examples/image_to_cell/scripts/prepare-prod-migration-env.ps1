# Pull production Supabase + crypto credentials from AWS Secrets Manager into
# backend/image-to-cell-3/.env.production for migrate_encrypt_webhook_secrets.py.
#
# Does NOT modify your local .env (dev/sandbox) or .env.staging.
# Run ONLY after prod-image-to-cell is deployed (SH-108 encrypts new writes; backfill
# converts existing plaintext rows in imagetocell_webhooks.shared_secret).
#
# Prereq: aws sso login --profile smarthub-production
# Usage (from repo root):
#   powershell -ExecutionPolicy Bypass -File backend/image-to-cell-3/scripts/prepare-prod-migration-env.ps1

param(
  [string] $Region = "eu-west-2",
  [string] $Profile = "smarthub-production",
  [string] $SecretId = "prod/image-to-cell-env"
)

$ErrorActionPreference = "Stop"
$OutDir = Split-Path -Parent $PSScriptRoot
$OutFile = Join-Path $OutDir ".env.production"

$acct = aws sts get-caller-identity --profile $Profile --query Account --output text
if ($acct -ne "296214942194") {
  throw "Expected Smarthub Production account 296214942194; got $acct. Check --profile $Profile"
}

$raw = aws secretsmanager get-secret-value `
  --secret-id $SecretId `
  --region $Region `
  --profile $Profile `
  --query "SecretString" `
  --output text

if (-not $raw) { throw "Empty SecretString from $SecretId" }

$obj = $raw | ConvertFrom-Json

$required = @("SUPABASE_URL", "SUPABASE_SERVICE_ROLE_KEY", "APP_CRYPTO_KEY")
$missing = @()
foreach ($key in $required) {
  $val = $obj.$key
  if ($null -eq $val -or [string]::IsNullOrWhiteSpace([string]$val)) {
    $missing += $key
  }
}
if ($missing.Count -gt 0) {
  throw "Secret $SecretId is missing: $($missing -join ', ')"
}

$lines = @(
  "# Auto-generated by prepare-prod-migration-env.ps1 - do not commit",
  "# Used only for: python scripts/migrate_encrypt_webhook_secrets.py --env-file .env.production",
  "",
  "SUPABASE_URL=$($obj.SUPABASE_URL)",
  "SUPABASE_SERVICE_ROLE_KEY=$($obj.SUPABASE_SERVICE_ROLE_KEY)",
  "APP_CRYPTO_KEY=$($obj.APP_CRYPTO_KEY)",
  ""
)

[System.IO.File]::WriteAllLines($OutFile, $lines, [System.Text.UTF8Encoding]::new($false))

$url = [string]$obj.SUPABASE_URL
Write-Host "Wrote $OutFile" -ForegroundColor Green
Write-Host "  Account    = $acct (Smarthub Production)" -ForegroundColor Cyan
Write-Host "  SUPABASE_URL = $url" -ForegroundColor Cyan
Write-Host "  SUPABASE_SERVICE_ROLE_KEY = (set, length $(([string]$obj.SUPABASE_SERVICE_ROLE_KEY).Length))" -ForegroundColor Cyan
Write-Host "  APP_CRYPTO_KEY = (set, length $(([string]$obj.APP_CRYPTO_KEY).Length))" -ForegroundColor Cyan
Write-Host ""
Write-Host "Next (after prod ECS rollout is healthy):" -ForegroundColor Yellow
Write-Host "  cd backend/image-to-cell-3"
Write-Host "  python scripts/migrate_encrypt_webhook_secrets.py --env-file .env.production --dry-run"
Write-Host "  python scripts/migrate_encrypt_webhook_secrets.py --env-file .env.production"
