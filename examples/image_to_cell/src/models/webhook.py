"""
Webhook Models
==============

Pydantic models for Smartsheet webhook events.
"""

from datetime import datetime
from enum import Enum
from typing import Optional, List, Any
from pydantic import BaseModel, Field


class WebhookEventType(str, Enum):
    """Known event types Smartsheet emits.

    Reference catalogue — NOT used to validate inbound payloads. Pydantic
    validation on the inbound event field uses a permissive ``str`` so that
    new event types added by Smartsheet do not crash the entire payload.
    Use ``.value`` for comparisons.
    """
    CREATED = "created"
    OBJECT_CREATED = "objectCreated"  # Smartsheet uses this for some create callbacks
    UPDATED = "updated"
    DELETED = "deleted"
    RESTORED = "restored"
    PURGED = "purged"


class WebhookObjectType(str, Enum):
    """Known object types Smartsheet emits.

    Reference catalogue — NOT used to validate inbound payloads. See
    ``WebhookEventType`` docstring for rationale. Use ``.value`` for
    comparisons.

    The strict subset i2c-3 acts on is ``ATTACHMENT``; the rest are ignored
    at the route level (see ``api/routes/webhooks.py`` filter).
    """
    # Types i2c-3 cares about
    ATTACHMENT = "attachment"
    # Other types Smartsheet emits — filtered out, not processed, but
    # listed here so they are valid inputs and so the unknown-types log
    # only fires for genuinely new types.
    ROW = "row"
    CELL = "cell"
    COLUMN = "column"
    SHEET = "sheet"
    DISCUSSION = "discussion"
    PROOF = "proof"
    REMINDER = "reminder"
    COMMENT = "comment"
    WORKSPACE = "workspace"
    FORM_ACCESS_KEY = "formAccessKey"


class WebhookEvent(BaseModel):
    """
    Single webhook event.

    Represents one change event from Smartsheet.

    Note: ``event_type`` and ``object_type`` are plain ``str`` (not Enum).
    Smartsheet adds new event/object types from time to time and a strict
    enum on the inbound side caused the entire payload to be rejected
    (production incident 2026-05-15 — see CHANGELOG and the test file
    ``tests/unit/test_webhook_payload_validation.py``). The ``Webhook*Type``
    enums above remain as the canonical reference list for code that needs
    to compare against known values.
    """

    event_type: str = Field(..., alias="eventType")
    object_type: str = Field(..., alias="objectType")
    object_id: Optional[int] = Field(None, alias="id")
    row_id: Optional[int] = Field(None, alias="rowId")
    column_id: Optional[int] = Field(None, alias="columnId")

    # For detecting self-generated changes
    change_agent: Optional[str] = Field(None, alias="changeAgent")

    # Timestamps
    timestamp: Optional[datetime] = None

    @property
    def is_attachment_event(self) -> bool:
        """Check if this is an attachment event."""
        return self.object_type == WebhookObjectType.ATTACHMENT.value

    @property
    def is_creation_event(self) -> bool:
        """Check if this is a creation event."""
        return self.event_type in (
            WebhookEventType.CREATED.value,
            WebhookEventType.OBJECT_CREATED.value,
        )

    @property
    def is_known_object_type(self) -> bool:
        """``True`` if ``object_type`` is in the catalogue of known types.

        Use to flag events Smartsheet starts sending that have not been
        seen before — they are still accepted and filtered, but operators
        may want to add them to the catalogue."""
        return self.object_type in {t.value for t in WebhookObjectType}

    @property
    def is_self_generated(self, our_agent_id: str = "smart-image-to-cell") -> bool:
        """Check if event was generated by our own changes."""
        if not self.change_agent:
            return False
        return our_agent_id in self.change_agent

    class Config:
        from_attributes = True
        populate_by_name = True


class WebhookPayload(BaseModel):
    """
    Complete webhook payload from Smartsheet.

    Contains all events and metadata from a single webhook call.
    """

    webhook_id: Optional[int] = Field(None, alias="webhookId")
    scope: str = Field(default="sheet")
    scope_object_id: Optional[int] = Field(None, alias="scopeObjectId")
    events: List[WebhookEvent] = Field(default_factory=list)

    # Challenge for verification
    challenge: Optional[str] = None

    # Callback metadata
    new_webhook_status: Optional[str] = Field(None, alias="newWebhookStatus")

    @property
    def worksheet_id(self) -> Optional[int]:
        """Get the worksheet ID from scope."""
        return self.scope_object_id

    @property
    def has_events(self) -> bool:
        """Check if payload contains events."""
        return len(self.events) > 0

    @property
    def attachment_events(self) -> List[WebhookEvent]:
        """Get only attachment-related events."""
        return [e for e in self.events if e.is_attachment_event]

    @property
    def new_attachment_events(self) -> List[WebhookEvent]:
        """Get only new attachment creation events."""
        return [
            e for e in self.events
            if e.is_attachment_event and e.is_creation_event
        ]

    class Config:
        from_attributes = True
        populate_by_name = True


class WebhookRegistration(BaseModel):
    """
    Webhook registration record.

    Stored in database to track registered webhooks.
    """

    webhook_id: int = Field(..., description="Smartsheet webhook ID")
    worksheet_id: int = Field(..., description="Worksheet the webhook is for")
    organization_id: str = Field(..., description="Organization ID")
    shared_secret: str = Field(..., description="HMAC secret for verification")
    webhook_url: Optional[str] = Field(None, description="Webhook callback URL")

    # Status
    status: str = Field(default="pending", description="Webhook status")
    enabled: bool = Field(default=True)

    # Timestamps
    registered_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None
    last_event_at: Optional[datetime] = None

    class Config:
        from_attributes = True


class WebhookVerification(BaseModel):
    """Model for webhook verification response."""

    smartsheet_hook_response: str = Field(
        ...,
        alias="smartsheetHookResponse",
        description="Challenge response to send back"
    )
